function cookName(baseName) {
  const mapped = COOK_NAME[baseName];
  if (mapped !== undefined) return mapped;
  let name = baseName
    .replace(/ \((Raw|Cured)\)$/, '')
    .replace(/ Spices$/, '');
  // "Spices, cloves, ground" and "Cloves, dried, ground": ground cloves.
  name = name.replace(/^(Spices?|Fish|Nuts?|Grains|Seeds), /, '');
  const ground = /, (dried, )?ground$/.exec(name);
  if (ground) name = `ground ${name.slice(0, ground.index)}`;
  // "bay leaf, whole" reads fine as it stands.
  return name.toLowerCase();
}

